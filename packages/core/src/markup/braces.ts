import { lowerElementTags } from './elementTags.js';

/**
 * Delimited variables (`#{name}`) and the enhanced arrow symbol (`<enhanced/>`), owner 2026-11-14.
 *
 * Both are authoring forms only. Every consumer, and the preview, reads the text lowered to the
 * legacy form (`lowerDelimitedMarkup`): `#{name}` becomes `#name` and `<enhanced/>` becomes `#e`
 * (the global variable e, the arrow), so every output is exactly what the legacy form builds.
 * Where the legacy form would merge with the letters or digits after it (`#{d}x` would read as
 * the variable `dx`), those letters move into a generated variable declared on the next line,
 * `#d#Zb1wx` + `var Zb1wx = x`, which the old converter resolves to the value of d followed by
 * "x" and then removes with the other declarations.
 */

/** The enhanced arrow as a symbol, like the icons (`<solar/>`). */
export const enhancedArrowMarkup = '<enhanced/>';
/** The legacy spelling of the arrow: the global variable e. Read forever, no longer offered. */
export const legacyEnhancedArrow = '#e';

/** A variable reference: `#{name}` (delimited) or `#name` (greedy, today's form). */
export const variableReferencePattern = /#\{([a-zA-Z0-9]+)\}|#([a-zA-Z0-9]+)/g;
/** `#e` written as the arrow: not followed by a letter or digit (that would be a longer name). */
export const legacyArrowPattern = /#e(?![a-zA-Z0-9])/g;

export interface VariableReference {
  /** The variable's name, without `#` or braces. */
  name: string;
  braced: boolean;
  from: number;
  to: number;
}

/** Every variable reference in `text`, in order, with offsets into `text`. */
export function variableReferences(text: string, offset = 0): VariableReference[] {
  if (!text.includes('#')) return [];
  const found: VariableReference[] = [];
  for (const match of text.matchAll(variableReferencePattern)) {
    const from = offset + match.index;
    found.push({
      name: match[1] ?? match[2]!,
      braced: match[1] !== undefined,
      from,
      to: from + match[0].length,
    });
  }
  return found;
}

/**
 * How the editor writes a reference to `name` (completions, Ctrl+Space, the markup bar, fixes):
 * always `#{name}`, so text typed after it never merges into the name (owner 2026-11-14). A typed
 * plain `#name` stays valid.
 */
export function writeVariable(name: string): string {
  return `#{${name}}`;
}

/** Whether `text` holds an authoring form the legacy pipeline does not read. */
export function hasDelimitedMarkup(text: string): boolean {
  return /#\{[a-zA-Z0-9]+\}/.test(text) || text.includes(enhancedArrowMarkup);
}

/**
 * The name of the generated variable that holds `word` (letters and digits). Prefix-free: no
 * holder name starts with another (the length comes before the word), because the old converter
 * replaces `#name` everywhere, also at the start of a longer reference. Equal words get equal
 * names and values, so documents that import each other never disagree about a holder.
 */
export const holderName = (word: string) => `Zb${word.length}w${word}`;
/** `#Zb1wx`: generated by lowering, never written by an author. */
export const holderPattern = /^Zb(\d+)w([a-zA-Z0-9]+)$/;
export function isHolderName(name: string): boolean {
  const match = holderPattern.exec(name);
  return match !== null && Number(match[1]) === match[2]!.length;
}

const delimited = /#\{([a-zA-Z0-9]+)\}|<enhanced\/>/g;

/**
 * The legacy form of `text`: exact and idempotent; text without `#{name}` or `<enhanced/>` comes
 * back as the same string. A form followed by letters or digits gets a holder variable for them,
 * declared on its own line right after the line that uses it (so it stays inside the same title,
 * export, condition block, or comment). `empty` is the converter's keyword for an empty value,
 * so that word is held in two parts.
 */
export function lowerDelimitedMarkup(text: string): string {
  if (!text.includes('#{') && !text.includes(enhancedArrowMarkup)) return text;
  const lines = text.split('\n');
  let changed = false;
  for (let index = 0; index < lines.length; index++) {
    const line = lines[index]!;
    if (!line.includes('#{') && !line.includes(enhancedArrowMarkup)) continue;
    const declarations: string[] = [];
    let out = '';
    let at = 0;
    for (const match of line.matchAll(delimited)) {
      if (match.index < at) continue;
      const legacy = match[1] === undefined ? legacyEnhancedArrow : `#${match[1]}`;
      const end = match.index + match[0].length;
      const word = /^[a-zA-Z0-9]+/.exec(line.slice(end))?.[0];
      out += line.slice(at, match.index) + legacy;
      at = end;
      if (word === undefined) continue;
      for (const part of word === 'empty' ? ['empt', 'y'] : [word]) {
        out += `#${holderName(part)}`;
        declarations.push(`var ${holderName(part)} = ${part}`);
      }
      at = end + word.length;
    }
    if (out === '' && at === 0) continue;
    changed = true;
    out += line.slice(at);
    // A line ending in \r (CRLF) keeps it; the declarations are plain lines after it.
    lines[index] = declarations.length ? [out, ...new Set(declarations)].join('\n') : out;
  }
  return changed ? lines.join('\n') : text;
}

/**
 * What every consumer reads: element tags (`<solar Scorch />`) and the delimited forms lowered to
 * the legacy format. Exact and idempotent.
 */
export function lowerConsumerMarkup(text: string): string {
  return lowerDelimitedMarkup(lowerElementTags(text));
}

/**
 * A markup-only edit: element tags, delimited variables, or the arrow symbol added, changed, or
 * removed (`<solar/>Scorch` and `<solar Scorch />`, `#d ` and `#{d} `, `#e` and `<enhanced/>`)
 * while the lowered text, what every consumer reads, stays exactly the same.
 */
export function isMarkupOnly(before: string | undefined, after: string): boolean {
  return (
    before !== undefined &&
    before !== after &&
    lowerConsumerMarkup(before) === lowerConsumerMarkup(after)
  );
}

/**
 * The longest defined name that the greedy reference `#name` starts with, when `name` itself is
 * not defined: `#dx` with only `var d` merges `d` with the text after it.
 */
export function mergedVariable(
  name: string,
  defined: (candidate: string) => boolean,
): string | undefined {
  if (defined(name)) return undefined;
  for (let length = name.length - 1; length > 0; length--) {
    const prefix = name.slice(0, length);
    if (defined(prefix)) return prefix;
  }
  return undefined;
}
