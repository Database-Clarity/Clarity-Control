import { z } from 'zod';
import {
  storedPersonalSnippetSchema,
  teamSnippetsSchema,
  type CustomSnippet,
  type SnippetChange,
} from '../../../../packages/core/src/customSnippets';
import { markupSnippets } from '@clarity/core';
import { apiRequest, failure } from './apiAuth';
import {
  effectiveSnippetsResponseSchema,
  localizedSnippetLangSchema,
  snippetTranslationsSchema,
  type SnippetTranslationChange,
} from '../../../../packages/core/src/localizedSnippets';

const personalResponseSchema = z.object({
  snippet: storedPersonalSnippetSchema.nullable(),
  revision: z.string().nullable(),
});
const personalIndexSchema = z.object({ snippets: z.array(personalResponseSchema).max(50) });
const teamResponseSchema = z.object({ team: teamSnippetsSchema });
export type PersonalSnippetResponse = z.infer<typeof personalResponseSchema>;
export type TeamSnippetsResponse = z.infer<typeof teamResponseSchema>;
export class SnippetConflictError extends Error {
  constructor(readonly current: unknown) {
    super('This snippet changed. Reload before saving.');
  }
}
async function request<T>(
  path: string,
  schema: z.ZodType<T>,
  value?: unknown,
  method = 'PUT',
): Promise<T> {
  const response = await apiRequest(
    path,
    value === undefined
      ? {}
      : {
          method,
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(value),
        },
  );
  if (response.status === 409) throw new SnippetConflictError(await response.json());
  if (!response.ok) return failure(response);
  return schema.parse(await response.json());
}
export const getPersonalSnippets = () => request('/snippets/mine', personalIndexSchema);
export const getPersonalSnippet = (id: string) =>
  request(`/snippets/mine/${encodeURIComponent(id)}`, personalResponseSchema);
/** Null deletes; revision null creates. Ids are generated by the caller as me:<uuid>. */
export const savePersonalSnippet = (
  id: string,
  snippet: CustomSnippet | null,
  revision: string | null,
) =>
  request(`/snippets/mine/${encodeURIComponent(id)}`, personalResponseSchema, {
    snippet,
    revision,
  });
export const getTeamSnippets = () => request('/snippets/team', teamResponseSchema);
/** Target-language effective catalogue; personal snippets remain a separate account read. */
export const getLocalizedSnippets = (language: string) =>
  request(
    `/snippets/local/${localizedSnippetLangSchema.parse(language)}`,
    effectiveSnippetsResponseSchema,
  );
/** Per-entry CAS: base null creates, next null deletes. enHash comes from the effective read. */
export const saveSnippetTranslation = (language: string, change: SnippetTranslationChange) =>
  request(
    `/snippets/local/${localizedSnippetLangSchema.parse(language)}`,
    z.object({ translations: snippetTranslationsSchema }),
    change,
  );
/** Compare-and-set for one entry: base null creates, next null deletes. */
export const saveTeamSnippet = (change: SnippetChange) =>
  request('/snippets/team', teamResponseSchema, change);
export const copyPersonalSnippetToTeam = (
  sourceId: string,
  sourceRevision: string,
  id: string,
  base: CustomSnippet | null = null,
) =>
  request(
    '/snippets/team/copy',
    teamResponseSchema,
    { sourceId, sourceRevision, id, base },
    'POST',
  );
/** Editor load failure shows built-ins only; Settings callers use the throwing APIs above. */
export async function loadEditorSnippets() {
  try {
    const [mine, team] = await Promise.all([getPersonalSnippets(), getTeamSnippets()]);
    return {
      builtIn: markupSnippets,
      mine: mine.snippets.flatMap((s) => (s.snippet ? [s.snippet] : [])),
      team: team.team.snippets,
    };
  } catch {
    return { builtIn: markupSnippets, mine: [] as CustomSnippet[], team: [] as CustomSnippet[] };
  }
}
